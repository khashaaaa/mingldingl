#!/usr/bin/env node
// Turns the Figma export (src/design/figma/*.json) into src/design/tokens.ts for the app and
// ../mingldingl_control/src/design/tokens.css for the admin. Rerun after re-exporting from Figma;
// never edit the outputs by hand.
const fs = require('node:fs');
const path = require('node:path');

const dir = path.join(__dirname, '..', 'src', 'design');
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, 'figma', f), 'utf8'));
const vars = read('variables.json');
const styles = read('text-styles.json');
const effects = read('effects.json');
const motion = read('motion.json');
const extras = read('extras.json');

const camel = (s) =>
  s.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : '')).replace(/^./, (c) => c.toLowerCase());
const kebab = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

// The font files @expo-google-fonts ships, keyed by Figma family + style.
const FONT = {
  'Pirata One/Regular': 'PirataOne_400Regular',
  'Yeseva One/Regular': 'YesevaOne_400Regular',
  'EB Garamond/Regular': 'EBGaramond_400Regular',
  'EB Garamond/Italic': 'EBGaramond_400Regular_Italic',
  'EB Garamond/SemiBold': 'EBGaramond_600SemiBold',
};
const font = (s) => {
  const f = FONT[`${s.family}/${s.style}`];
  if (!f) throw new Error(`No font file for ${s.family} ${s.style}`);
  return f;
};

const primitive = Object.fromEntries(Object.entries(vars.primitives).map(([k, v]) => [camel(k), v]));
const color = Object.fromEntries(Object.entries(vars.color).map(([k, v]) => [camel(k), v.value]));
const dimension = Object.fromEntries(Object.entries(vars.dimension).map(([k, v]) => [camel(k), v]));

const textStyle = (s) => ({
  fontFamily: font(s),
  fontSize: s.size,
  lineHeight: s.lineHeight,
  letterSpacing: Math.round(s.size * (s.letterSpacingPercent / 100) * 100) / 100,
  ...(s.textCase === 'UPPER' ? { textTransform: 'uppercase' } : {}),
});
const type = {};
const typeMn = {};
for (const s of styles) {
  if (s.name.endsWith(' MN')) continue;
  type[camel(s.name)] = textStyle(s);
}
Object.assign(typeMn, type);
for (const s of styles.filter((x) => x.name.endsWith(' MN')))
  typeMn[camel(s.name.replace(/ MN$/, ''))] = textStyle(s);

const effect = Object.fromEntries(Object.entries(effects).map(([k, v]) => [camel(k), v]));

const d = motion.durations;
const easing = {};
for (const [k, v] of Object.entries(motion.easings)) easing[k] = v.bezier ?? v.spring;

const header =
  '// Generated by scripts/gen-tokens.js from the Figma export in src/design/figma. Do not edit.\n';
const ts = `${header}
export const primitive = ${JSON.stringify(primitive, null, 2)} as const;

export const color = ${JSON.stringify(color, null, 2)} as const;

export const dimension = ${JSON.stringify(dimension, null, 2)} as const;

export type TextStyle = {
  fontFamily: string;
  fontSize: number;
  lineHeight: number;
  letterSpacing: number;
  textTransform?: 'uppercase';
};

export const type = ${JSON.stringify(type, null, 2)} as const satisfies Record<string, TextStyle>;

/** Mongolian overrides: blackletter has no Cyrillic, so room titles switch to Yeseva One. */
export const typeMn = ${JSON.stringify(typeMn, null, 2)} as const satisfies Record<string, TextStyle>;

export type TypeName = keyof typeof type;

export type Effect = { type: 'DROP_SHADOW' | 'INNER_SHADOW'; radius: number; color: string; opacity: number; x: number; y: number };

export const effect = ${JSON.stringify(effect, null, 2)} as const satisfies Record<string, readonly Effect[]>;

export const duration = {
  tap: ${d.tap},
  shift: ${d.shift},
  travel: ${d.travel},
  ceremonyMin: ${d.ceremonyMin},
  ceremonyMax: ${d.ceremonyMax},
  loopMin: ${d.loopMin},
  loopMax: ${d.loopMax},
  /** M3: an exit takes ${motion.exitRatio * 100}% of its entrance. */
  exit: (entrance: number) => Math.round(entrance * ${motion.exitRatio}),
} as const;

/** Raw values Figma keeps inside components (not variables) — see figma/extras.json. */
export const component = ${JSON.stringify((({ source, ...rest }) => rest)(extras), null, 2)} as const;

export const easing = {
  forgeOut: ${JSON.stringify(easing.forgeOut)} as const,
  emberIn: ${JSON.stringify(easing.emberIn)} as const,
  breathe: ${JSON.stringify(easing.breathe)} as const,
  anvil: ${JSON.stringify(easing.anvil)} as const,
};
`;
fs.writeFileSync(path.join(dir, 'tokens.ts'), ts);

const css = [`/* Generated by mingldingl_app/scripts/gen-tokens.js from Figma. Do not edit. */`, ':root {'];
for (const [k, v] of Object.entries(vars.primitives)) css.push(`  --${kebab(k)}: ${v};`);
for (const [k, v] of Object.entries(vars.color)) css.push(`  --color-${kebab(k)}: var(--${kebab(v.alias)});`);
for (const [k, v] of Object.entries(vars.dimension)) css.push(`  --${kebab(k)}: ${v}px;`);
for (const s of styles) {
  const n = kebab(s.name);
  css.push(
    `  --font-${n}: ${s.style === 'Italic' ? 'italic ' : ''}${s.style === 'SemiBold' ? 600 : 400} ${s.size}px/${s.lineHeight}px '${s.family}';`,
  );
  if (s.letterSpacingPercent) css.push(`  --tracking-${n}: ${s.letterSpacingPercent / 100}em;`);
}
css.push(
  `  --duration-tap: ${d.tap}ms;`,
  `  --duration-shift: ${d.shift}ms;`,
  `  --duration-travel: ${d.travel}ms;`,
);
for (const k of ['forgeOut', 'emberIn', 'breathe'])
  css.push(`  --ease-${kebab(k.replace(/[A-Z]/g, (c) => `-${c}`))}: cubic-bezier(${easing[k].join(', ')});`);
css.push('}', '');
const cssPath = path.join(__dirname, '..', '..', 'mingldingl_control', 'src', 'design', 'tokens.css');
fs.mkdirSync(path.dirname(cssPath), { recursive: true });
fs.writeFileSync(cssPath, css.join('\n'));
console.log(
  `tokens.ts: ${Object.keys(color).length} colours, ${Object.keys(type).length} text styles; tokens.css written`,
);

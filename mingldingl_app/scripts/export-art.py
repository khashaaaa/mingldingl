#!/usr/bin/env python3
"""Downloads every art image named in src/design/figma/art.json from the Figma file at full source
resolution (by image hash), trims nothing, and writes name.webp / @2x / @3x sized to its display
size in points (lossy WebP, a quarter of the PNG; a scale the source is too small for is left out,
so the device uses the one below). Then writes src/design/art/manifest.ts. Token: $FIGMA_TOKEN or ~/.figma-token."""
import io, json, os, pathlib, urllib.request
from PIL import Image

FILE = "nLwcONhTplnnOmXu3wroIx"
root = pathlib.Path(__file__).resolve().parent.parent
spec = json.loads((root / "src/design/figma/art.json").read_text())
out = root / "src/design/art"
out.mkdir(parents=True, exist_ok=True)
token = os.environ.get("FIGMA_TOKEN") or (pathlib.Path.home() / ".figma-token").read_text().strip()

def get(url, auth=True):
    req = urllib.request.Request(url, headers={"X-Figma-Token": token} if auth else {})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()

urls = json.loads(get(f"https://api.figma.com/v1/files/{FILE}/images"))["meta"]["images"]
WEBP_QUALITY = 90
cache = pathlib.Path("/tmp") / "mingl-figma-art"
cache.mkdir(exist_ok=True)
for name, s in spec.items():
    if (out / f"{name}.webp").exists() and os.environ.get("ART_FORCE") != "1":
        continue
    full = [h for h in urls if h.startswith(s["hash"])]
    if len(full) != 1:
        raise SystemExit(f"{name}: hash {s['hash']} matched {len(full)} images")
    src = cache / f"{full[0]}.png"
    if not src.exists():
        src.write_bytes(get(urls[full[0]], auth=False))
    img = Image.open(src).convert("RGBA")
    last = None
    for scale, suffix in ((1, ""), (2, "@2x"), (3, "@3x")):
        box = (s["w"] * scale, s["h"] * scale)
        # "contain" fits inside the box (Figma FIT); "cover" fills it and the device crops (Figma FILL).
        # Either way aspect is kept and the source is never upscaled.
        pick = min if s["fit"] == "contain" else max
        r = min(pick(box[0] / img.width, box[1] / img.height), 1.0)
        size = (max(1, round(img.width * r)), max(1, round(img.height * r)))
        if size == last:
            continue
        last = size
        img.resize(size, Image.LANCZOS).save(out / f"{name}{suffix}.webp", quality=WEBP_QUALITY, method=6)
    print(f"{name}: source {img.width}x{img.height}")

# The web page uses Figma's static sparks; the app draws live particles instead, so this asset
# belongs only to the web bundle. Source: Ember Glow / Fire=Lit, layer 148:94 (390 x 550 points).
web_sparks = root.parent / "mingldingl_control/src/design/art/ember_sparks.webp"
if not web_sparks.exists() or os.environ.get("ART_FORCE") == "1":
    spark_hash = "751fa8ecf651221ec7d9853db6633fea5551963c"
    spark_image = Image.open(io.BytesIO(get(urls[spark_hash], auth=False))).convert("RGBA")
    web_sparks.parent.mkdir(parents=True, exist_ok=True)
    spark_image.save(web_sparks, quality=WEBP_QUALITY, method=6)

lines = ["// Generated by scripts/export-art.py from the Figma file. Do not edit.", "", "export const ART = {"]
for name in sorted(spec):
    lines.append(f"  {name}: require('./{name}.webp'),")
lines += ["} as const;", "", "export type ArtName = keyof typeof ART;", ""]
(out / "manifest.ts").write_text("\n".join(lines))

# Glyphs: rendered by Figma from the 24 pt vector components at 1/2/3x (24/48/72 px), shown as
# tinted images (only alpha matters).
glyphs = json.loads((root / "src/design/figma/glyphs.json").read_text())
gdir = root / "src/design/glyphs"
gdir.mkdir(parents=True, exist_ok=True)
ids = ",".join(glyphs.values())
for scale, suffix in ((1, ""), (2, "@2x"), (3, "@3x")):
    res = json.loads(get(f"https://api.figma.com/v1/images/{FILE}?ids={ids}&format=png&scale={scale}"))
    for name, node in glyphs.items():
        png = Image.open(io.BytesIO(get(res["images"][node], auth=False))).convert("RGBA")
        png.save(gdir / f"{name}{suffix}.png", optimize=True)
glines = ["// Generated by scripts/export-art.py from Figma page 05. Do not edit.", "", "export const GLYPHS = {"]
for name in sorted(glyphs):
    glines.append(f"  '{name}': require('./{name}.png'),")
glines += ["} as const;", "", "export type GlyphName = keyof typeof GLYPHS;", ""]
(gdir / "index.ts").write_text("\n".join(glines))
print(f"{len(glyphs)} glyphs")
